#!/usr/bin/env node
/**
 * Compile `assets/icons/warsha/*.svg` into one shared geometry module.
 *
 * The approved icons are SVG files. Native cannot import an SVG file, web can,
 * and neither should hold a second copy of a path — a shape that exists twice
 * is a shape that will differ. So the files are the source, this compiles them
 * into structured data once, and the native and web renderers both draw from
 * that.
 *
 * `--check` re-derives and compares instead of writing, which is what the
 * regression suite runs: editing an SVG without recompiling, or hand-editing
 * the generated module, fails rather than shipping a silent divergence.
 *
 * Deliberately strict. The family uses four element types and a closed set of
 * attributes; anything else is a file that was not produced by the approved
 * pipeline, and guessing at it would be how an unreviewed shape gets in.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ASSET_DIR = 'assets/icons/warsha';
const OUTPUT = 'src/brand/warsha-icon-geometry.ts';

const ALLOWED_ELEMENTS = new Set(['path', 'rect', 'circle', 'ellipse']);
const ALLOWED_ATTRIBUTES = new Set([
  'd', 'x', 'y', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r',
  'transform', 'fill', 'stroke',
]);

export function iconStems() {
  return readdirSync(ASSET_DIR).filter((name) => name.endsWith('.svg'))
    .map((name) => name.slice(0, -'.svg'.length)).sort();
}

function parseAsset(stem) {
  const source = readFileSync(join(ASSET_DIR, `${stem}.svg`), 'utf8');

  const root = /<svg\b([^>]*)>/.exec(source);
  if (!root) throw new Error(`${stem}: no <svg> root`);
  if (!/viewBox="0 0 24 24"/.test(root[1])) throw new Error(`${stem}: viewBox must be 0 0 24 24`);
  if (!/stroke="currentColor"/.test(root[1])) throw new Error(`${stem}: root must stroke currentColor`);
  if (!/stroke-width="1.75"/.test(root[1])) throw new Error(`${stem}: stroke width must be 1.75`);
  if (/<image\b|xlink:href|<text\b|<style\b|@font-face/.test(source)) {
    throw new Error(`${stem}: raster, text or font content is not allowed`);
  }
  if (/(?:#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(|\b(?:black|white|red|green|blue)\b)/.test(source)) {
    throw new Error(`${stem}: a fixed presentation colour is not allowed`);
  }

  const elements = [];
  for (const match of source.matchAll(/<(path|rect|circle|ellipse)\b([^>]*?)\/?>/g)) {
    const [, tag, rawAttributes] = match;
    if (!ALLOWED_ELEMENTS.has(tag)) throw new Error(`${stem}: unsupported element <${tag}>`);
    const attributes = {};
    for (const attribute of rawAttributes.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      const [, name, value] = attribute;
      if (!ALLOWED_ATTRIBUTES.has(name)) throw new Error(`${stem}: unsupported attribute ${name}`);
      attributes[name] = value;
    }
    if (attributes.fill && attributes.fill !== 'none' && attributes.fill !== 'currentColor') {
      throw new Error(`${stem}: fill must be none or currentColor`);
    }
    elements.push({ tag, ...attributes });
  }
  if (elements.length === 0) throw new Error(`${stem}: no drawn elements`);
  if (elements.length > 6) throw new Error(`${stem}: more than six drawn elements`);
  return elements;
}

export function compile() {
  const stems = iconStems();
  const lines = [];
  lines.push('/**');
  lines.push(' * The approved Warsha icon family, as data.');
  lines.push(' *');
  lines.push(' * GENERATED by `scripts/generate-warsha-icon-geometry.mjs` from the SVG files in');
  lines.push(' * `assets/icons/warsha/`. Do not edit by hand — `warsha-icons.test.mts` recompiles');
  lines.push(' * the assets and fails if this file disagrees with them.');
  lines.push(' *');
  lines.push(' * The geometry lives here, once, because native cannot import an SVG file and');
  lines.push(' * web can. Keeping a copy on each side is how two platforms end up drawing');
  lines.push(' * subtly different marks; `WarshaIcon` on native and `WarshaIcon` on web both');
  lines.push(' * render these same elements.');
  lines.push(' */');
  lines.push('');
  lines.push('/** One drawn element. `fill: currentColor` marks the single solid accent. */');
  lines.push('export type WarshaIconElement = {');
  lines.push("  tag: 'path' | 'rect' | 'circle' | 'ellipse';");
  lines.push('  d?: string;');
  lines.push('  x?: string; y?: string; width?: string; height?: string;');
  lines.push('  rx?: string; ry?: string;');
  lines.push('  cx?: string; cy?: string; r?: string;');
  lines.push('  transform?: string;');
  lines.push("  fill?: 'none' | 'currentColor';");
  lines.push("  stroke?: 'none';");
  lines.push('};');
  lines.push('');
  lines.push('/** Every icon draws on a 24x24 grid with a 1.75 stroke. One family, no variants. */');
  lines.push("export const WARSHA_ICON_VIEWBOX = '0 0 24 24' as const;");
  lines.push('export const WARSHA_ICON_STROKE_WIDTH = 1.75 as const;');
  lines.push('');
  lines.push('export const warshaIconGeometry = {');
  for (const stem of stems) {
    lines.push(`  '${stem}': [`);
    for (const element of parseAsset(stem)) {
      const parts = Object.entries(element).map(([key, value]) => `${key}: '${value}'`);
      lines.push(`    { ${parts.join(', ')} },`);
    }
    lines.push('  ],');
  }
  lines.push('} as const satisfies Record<string, readonly WarshaIconElement[]>;');
  lines.push('');
  lines.push('export type WarshaIconName = keyof typeof warshaIconGeometry;');
  lines.push('');
  lines.push('export function warshaIconElements(name: string): readonly WarshaIconElement[] | null {');
  lines.push('  return (warshaIconGeometry as Record<string, readonly WarshaIconElement[]>)[name] ?? null;');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

const compiled = compile();
if (process.argv.includes('--check')) {
  const existing = readFileSync(OUTPUT, 'utf8');
  if (existing !== compiled) {
    console.error(`${OUTPUT} does not match the assets. Run: node scripts/generate-warsha-icon-geometry.mjs`);
    process.exit(1);
  }
  console.log(`Icon geometry matches ${iconStems().length} approved assets.`);
} else {
  writeFileSync(OUTPUT, compiled, 'utf8');
  console.log(`Compiled ${iconStems().length} approved assets into ${OUTPUT}.`);
}
