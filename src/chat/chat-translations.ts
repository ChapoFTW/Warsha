export function useChatText() {
  const { language } = useLocalization();
  return (key: ChatCopyKey) => copy[language][key];
}
export const quickReplyCopyKey = (key: QuickReplyKey) => `quick_${key}` as ChatCopyKey;
export const abuseCategoryCopyKey = (category: AbuseCategory) => `category_${category}` as ChatCopyKey;
